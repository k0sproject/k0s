// Identifier identifies a versioned Kubernetes resource schema.
type Identifier struct {
	APIVersion string
	Kind       string
}

func (id Identifier) String() string {
	return id.APIVersion + " " + id.Kind
}

// List returns the schemas embedded in k0s, ordered by API version and kind.
func List() ([]Identifier, error) {
	crds, err := crds()
	if err != nil {
		return nil, err
	}
	var ids []Identifier
	for _, crd := range crds {
		for _, version := range crd.Spec.Versions {
			if version.Schema == nil || version.Schema.OpenAPIV3Schema == nil {
				continue
			}
			ids = append(ids, Identifier{APIVersion: crd.Spec.Group + "/" + version.Name, Kind: crd.Spec.Names.Kind})
		}
	}
	slices.SortFunc(ids, func(a, b Identifier) int {
		if a.APIVersion == b.APIVersion {
			return strings.Compare(a.Kind, b.Kind)
		}
		return strings.Compare(a.APIVersion, b.APIVersion)
	})
	return ids, nil
}

// Generate returns the draft-07 schema for apiVersion and kind.
func Generate(apiVersion, kind string) ([]byte, error) {
	crds, err := crds()
	if err != nil {
		return nil, err
	}
	for _, crd := range crds {
		if crd.Spec.Names.Kind != kind {
			continue
		}
		for _, version := range crd.Spec.Versions {
			if crd.Spec.Group+"/"+version.Name != apiVersion || version.Schema == nil || version.Schema.OpenAPIV3Schema == nil {
				continue
			}
			return generate(apiVersion, kind, version.Schema.OpenAPIV3Schema)
		}
	}
	return nil, fmt.Errorf("no schema for %s %s", apiVersion, kind)
}

func crds() ([]apiextensionsv1.CustomResourceDefinition, error) {
	var crds []apiextensionsv1.CustomResourceDefinition
	err := fs.WalkDir(static.CRDs, ".", func(name string, entry fs.DirEntry, err error) error {
		if err != nil || entry.IsDir() || path.Ext(name) != ".yaml" {
			return err
		}
		data, err := fs.ReadFile(static.CRDs, name)
		if err != nil {
			return err
		}
		var crd apiextensionsv1.CustomResourceDefinition
		if err := yaml.Unmarshal(data, &crd); err != nil {
			return fmt.Errorf("read CRD %q: %w", name, err)
		}
		crds = append(crds, crd)
		return nil
	})
	return crds, err
}

func generate(apiVersion, kind string, source *apiextensionsv1.JSONSchemaProps) ([]byte, error) {
	data, err := json.Marshal(source)
	if err != nil {
		return nil, err
	}
	var openAPI map[string]any
	if err := json.Unmarshal(data, &openAPI); err != nil {
		return nil, err
	}
	schema, err := structuralSchema(openAPI, false, true)
	if err != nil {
		return nil, err
	}
	schema["$schema"] = "http://json-schema.org/draft-07/schema#"
	schema["title"] = "k0s " + kind + " (" + apiVersion + ")"
	schema["$comment"] = "Generated by k0s docs json-schema. Do not edit this generated file directly. Use k0s config validate for additional semantic validation."
	data, err = json.MarshalIndent(schema, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}

// structuralSchema translates the OpenAPI features used by k0s CRDs to JSON
// Schema draft-07. Reject unsupported features rather than silently changing
// validation semantics when a CRD evolves. Patterns are copied unchanged;
// JSON Schema recommends a portable regular-expression subset:
// https://json-schema.org/draft-07/json-schema-validation.html#rfc.section.4.3.
func structuralSchema(source map[string]any, openObject, root bool) (map[string]any, error) {
	schema := maps.Clone(source)
	preserveUnknown, _ := source["x-kubernetes-preserve-unknown-fields"].(bool)
	if source["type"] == "object" && !openObject && !preserveUnknown {
		if _, ok := source["additionalProperties"]; !ok {
			schema["additionalProperties"] = false
		}
	}
	var validationSchemas []map[string]any
	for key := range source {
		switch key {
		case "default", "description", "enum", "maxItems", "maxLength", "maximum",
			"minItems", "minLength", "minimum", "pattern", "required", "type":
		case "format":
			switch source[key] {
			case "date-time":
				if source["type"] != "string" {
					return nil, fmt.Errorf("unsupported format %v for type %v", source[key], source["type"])
				}
			case "int32":
				if source["type"] != "integer" {
					return nil, fmt.Errorf("unsupported format %v for type %v", source[key], source["type"])
				}
				if minimum, ok := source["minimum"].(float64); !ok || minimum < math.MinInt32 {
					schema["minimum"] = float64(math.MinInt32)
				}
				if maximum, ok := source["maximum"].(float64); !ok || maximum > math.MaxInt32 {
					schema["maximum"] = float64(math.MaxInt32)
				}
			case "int64":
				if source["type"] != "integer" {
					return nil, fmt.Errorf("unsupported format %v for type %v", source[key], source["type"])
				}
				if _, ok := source["minimum"]; !ok {
					schema["minimum"] = json.Number(strconv.FormatInt(math.MinInt64, 10))
				}
				if _, ok := source["maximum"]; !ok {
					schema["maximum"] = json.Number(strconv.FormatInt(math.MaxInt64, 10))
				}
			default:
				return nil, fmt.Errorf("unsupported format %v for type %v", source[key], source["type"])
			}
		case "x-kubernetes-int-or-string":
			if source[key] == true {
				schema["type"] = []any{"integer", "string"}
			}
			delete(schema, key)
		case "x-kubernetes-list-type", "x-kubernetes-list-map-keys", "x-kubernetes-preserve-unknown-fields":
			delete(schema, key)
		case "x-kubernetes-validations":
			delete(schema, key)
			validations, err := cast[[]any](source[key])
			if err != nil {
				return nil, fmt.Errorf(`x-kubernetes-validations: %w`, err)
			}
			validationSchemas, err = validationRulesToJSONSchemas(validations, source["type"])
			if err != nil {
				return nil, fmt.Errorf(`x-kubernetes-validations: failed to produce JSON Schemas for CEL validation rules: %w`, err)
			}
		case "properties":
			properties := source[key].(map[string]any)
			converted := make(map[string]any, len(properties))
			for name, property := range properties {
				child, err := structuralSchema(property.(map[string]any), openObject || (root && name == "metadata"), false)
				if err != nil {
					return nil, fmt.Errorf("property %q: %w", name, err)
				}
				converted[name] = child
			}
			schema[key] = converted
		case "items", "additionalProperties":
			if child, ok := source[key].(map[string]any); ok {
				converted, err := structuralSchema(child, false, false)
				if err != nil {
					return nil, fmt.Errorf("%s: %w", key, err)
				}
				schema[key] = converted
			}
		default:
			return nil, fmt.Errorf("unsupported schema keyword %q", key)
		}
	}
	// Merge once all keywords are converted, so that the merge only sees and
	// touches what belongs to the converted schema.
	for _, validationSchema := range validationSchemas {
		mergeJSONSchemas(schema, validationSchema)
	}
	return schema, nil
}

// Converts each CEL validation rule into a JSON Schema.
func validationRulesToJSONSchemas(validations []any, schemaType any) (schemas []map[string]any, _ error) {
	if schemaType != "string" {
		return nil, fmt.Errorf("%w: schema type %v", errors.ErrUnsupported, schemaType)
	}
	parser, err := celparser.NewParser()
	if err != nil {
		return nil, err
	}

	for i, validation := range validations {
		validation, err := cast[map[string]any](validation)
		if err != nil {
			return nil, fmt.Errorf("validation %d: %w", i, err)
		}
		rule, err := cast[string](validation["rule"])
		if err != nil {
			return nil, fmt.Errorf("validation %d: failed to get rule: %w", i, err)
		}
		ast, errs := parser.Parse(celcommon.NewTextSource(rule))
		if errs := errs.GetErrors(); len(errs) > 0 {
			return nil, fmt.Errorf("rule %q: %s", rule, errs[0].Message)
		}
		schema, err := celExpressionToJSONSchema(ast.Expr())
		if err != nil {
			return nil, fmt.Errorf("rule %q: %w", rule, err)
		}
		schemas = append(schemas, schema)
	}

	return
}

// Converts the CEL expression into a JSON Schema.
func celExpressionToJSONSchema(e celast.Expr) (map[string]any, error) {
	if e.Kind() != celast.CallKind {
		return nil, fmt.Errorf("%w: not a function call", errors.ErrUnsupported)
	}

	call := e.AsCall()
	fn := call.FunctionName()

	// Handle string predicates on self and convert them to RE2 regexes.
	if call.IsMemberFunction() {
		target := call.Target()
		if target.Kind() != celast.IdentKind {
			return nil, fmt.Errorf("%w: function call \"%s\" is not targeting self", errors.ErrUnsupported, fn)
		}
		ident := target.AsIdent()
		if ident != "self" {
			return nil, fmt.Errorf("%w: function call \"%v.%s\" is not targeting self", errors.ErrUnsupported, ident, fn)
		}
		if len(call.Args()) != 1 || call.Args()[0].Kind() != celast.LiteralKind {
			return nil, fmt.Errorf("%w: function call \"%v.%s\" is not receiving a single literal string", errors.ErrUnsupported, ident, fn)
		}
		var arg string
		if lit, ok := call.Args()[0].AsLiteral().(celtypes.String); !ok {
			return nil, fmt.Errorf(
				"%w: function call \"%v.%s\" is not receiving a single literal string", errors.ErrUnsupported, ident, fn)
		} else {
			arg = string(lit)
		}

		var pattern string
		switch fn {
		case "contains":
			pattern = regexp.QuoteMeta(arg)
		case "startsWith":
			pattern = "^" + regexp.QuoteMeta(arg)
		case "endsWith":
			pattern = regexp.QuoteMeta(arg) + "$"
		case "matches":
			pattern = arg
		default:
			return nil, fmt.Errorf("%w: function call \"%v.%s\"", errors.ErrUnsupported, ident, fn)
		}

		return map[string]any{"pattern": pattern}, nil
	}

	// Resolve "&&", "||" and "!"
	var keyword string
	switch fn {
	case celoperators.LogicalAnd:
		keyword = "allOf"
	case celoperators.LogicalOr:
		keyword = "anyOf"
	case celoperators.LogicalNot:
		schema, err := celExpressionToJSONSchema(call.Args()[0])
		if err != nil {
			return nil, err
		}
		return map[string]any{"not": schema}, nil
	default:
		return nil, fmt.Errorf("%w: function call \"%s\"", errors.ErrUnsupported, fn)
	}

	var schemas []any
	for _, operand := range call.Args() {
		schema, err := celExpressionToJSONSchema(operand)
		if err != nil {
			return nil, err
		}
		// Flatten operands of the same operator.
		if nested, ok := schema[keyword].([]any); ok {
			schemas = append(schemas, nested...)
		} else {
			schemas = append(schemas, schema)
		}
	}
	return map[string]any{keyword: schemas}, nil
}

// Merges from into the JSON Schema into, so that into accepts what both schemas accept.
func mergeJSONSchemas(into, from map[string]any) {
	conflicts := map[string]any{}
	for keyword, value := range from {
		switch keyword {
		case "allOf", "anyOf", "not", "pattern":
		default:
			panic("keyword handling not implemented for " + keyword)
		}

		existing, exists := into[keyword]
		switch {
		case !exists:
			into[keyword] = value
		case reflect.DeepEqual(existing, value):
		case keyword == "allOf":
			// Clip, so that appending never writes into a shared array.
			into[keyword] = append(slices.Clip(existing.([]any)), value.([]any)...)
		default:
			conflicts[keyword] = value
		}
	}

	if len(conflicts) > 0 {
		allOf, _ := into["allOf"].([]any)
		into["allOf"] = append(slices.Clip(allOf), conflicts)
	}
}

func cast[T any](x any) (T, error) {
	t, ok := x.(T)
	if ok {
		return t, nil
	}
	return t, fmt.Errorf("expected %T, got %T", t, x)
}
